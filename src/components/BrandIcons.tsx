import type { ReactNode } from "react";

// lucide-react 1.0 removed its brand icons. These draw the same outlines
// (paths from lucide-react 0.577, ISC licence), so the footer and team
// cards look unchanged on either version.

interface IconProps {
  size?: number;
}

function OutlineIcon({ size = 24, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

export function Instagram({ size }: IconProps) {
  return (
    <OutlineIcon size={size}>
      <rect width="20" height="20" x="2" y="2" rx="5" ry="5" />
      <path d="M16 11.37A4 4 0 1 1 12.63 8 4 4 0 0 1 16 11.37z" />
      <line x1="17.5" x2="17.51" y1="6.5" y2="6.5" />
    </OutlineIcon>
  );
}

export function Linkedin({ size }: IconProps) {
  return (
    <OutlineIcon size={size}>
      <path d="M16 8a6 6 0 0 1 6 6v7h-4v-7a2 2 0 0 0-2-2 2 2 0 0 0-2 2v7h-4v-7a6 6 0 0 1 6-6z" />
      <rect width="4" height="12" x="2" y="9" />
      <circle cx="4" cy="4" r="2" />
    </OutlineIcon>
  );
}
